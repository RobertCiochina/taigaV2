QString csvEscapeField(QString s) {
  if (s.contains(u',') || s.contains(u'"') || s.contains(u'\n') || s.contains(u'\r')) {
    s.replace(QLatin1Char{'"'}, QStringLiteral("\"\""));
    return QLatin1Char{'"'} + s + QLatin1Char{'"'};
  }
  return s;
}

